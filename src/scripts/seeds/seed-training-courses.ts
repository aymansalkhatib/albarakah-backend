import { QueryRunner } from 'typeorm';
import { TrainingCourse } from '../../modules/training-courses/entities/training-course.entity';

export async function seedTrainingCourses(queryRunner: QueryRunner) {
  const trainingCourseRepo = queryRunner.manager.getRepository(TrainingCourse);

  for (const courseData of trainingCoursesData) {
    const existingCourse = await trainingCourseRepo.findOne({
      where: { name: courseData.name },
    });

    if (existingCourse) {
      console.log(
        `❌ Training course with name "${courseData.name}" already exists`,
      );
      continue;
    }

    await trainingCourseRepo.save(trainingCourseRepo.create(courseData));
  }

  console.log('🎉 Training courses seeding completed successfully!');
}

